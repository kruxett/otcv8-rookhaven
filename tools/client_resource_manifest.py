"""Bind the executable to the exact resource set, including deterministic LuaJIT bytecode.

No secret or self-reported checksum is used to authorize scripts. Changing any
resource requires rebuilding the executable and shipping the matching pair.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import subprocess
import tempfile


def generate(root, output, compiler):
    root, output, compiler = Path(root).resolve(), Path(output).resolve(), Path(compiler).resolve()
    files = [root / 'init.lua']
    for folder in ('data', 'modules', 'layouts'):
        files.extend(p for p in (root / folder).rglob('*') if p.is_file())
    entries = {}
    env = os.environ.copy()
    env['LUA_PATH'] = f'{compiler.parent.as_posix()}/lua/?.lua;{compiler.parent.as_posix()}/lua/?/init.lua;;'
    env.pop('LUA_INIT', None)
    with tempfile.TemporaryDirectory(prefix='rookhaven-manifest-') as temp:
        compiled = Path(temp) / 'resource.luac'
        for path in sorted(files):
            relative = path.relative_to(root).as_posix()
            if path.is_symlink() or any(part in ('game_bot', 'client_terminal') for part in path.parts):
                raise ValueError(f'Forbidden resource: {relative}')
            if path.suffix == '.lua' and (relative.startswith(('data/', 'modules/')) or relative == 'init.lua'):
                subprocess.run([str(compiler), '-b', '-d', str(path), str(compiled)], env=env, check=True,
                               stdout=subprocess.PIPE, stderr=subprocess.PIPE)
                data = compiled.read_bytes()
                relative = relative[:-4] + '.luac'
            else:
                data = path.read_bytes()
            key = '/' + relative
            if key in entries:
                raise ValueError(f'Duplicate resource: {key}')
            entries[key] = {'sha256': hashlib.sha256(data).hexdigest(), 'size': len(data)}
    entries = dict(sorted(entries.items()))
    fingerprint = hashlib.sha256(''.join(f'{p}\0{v["sha256"]}\n' for p, v in entries.items()).encode()).hexdigest()
    lines = ['// Generated by client_resource_manifest.py; do not edit.', '#pragma once',
             '#include <map>', '#include <string>', '#include <cstddef>',
             'namespace RookhavenResources {', 'struct Entry { const char* hash; size_t size; };',
             f'inline constexpr const char* fingerprint = "{fingerprint}";',
             'inline const std::map<std::string, Entry> files = {']
    lines += [f'    {{{json.dumps(p)}, {{"{v["sha256"]}", {v["size"]}}}}},' for p, v in entries.items()]
    lines += ['};', '}']
    output.parent.mkdir(parents=True, exist_ok=True)
    header = '\n'.join(lines) + '\n'
    if not output.exists() or output.read_text() != header:
        output.write_text(header, encoding='utf-8', newline='\n')
    output.with_suffix('.json').write_text(json.dumps({'fingerprint': fingerprint, 'files': entries}, indent=2)+'\n')
    print(f'Approved {len(entries)} resources: {fingerprint}')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--root', required=True)
    parser.add_argument('--output', required=True)
    parser.add_argument('--luajit', required=True)
    args = parser.parse_args()
    generate(args.root, args.output, args.luajit)
